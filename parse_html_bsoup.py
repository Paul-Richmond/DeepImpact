"""
parse_html_bsoup.py - This script processes HTML files, extracts comment data using BeautifulSoup, and writes the 
results to JSON files. It currently supports extracting BBC-style comment information, such as comment content,
usernames, timestamps, likes, and dislikes.

It can be used as a fallback when the LLM results generated by parse_html.py are not reliable.

It also adds a thread_id and a reply flag to help identify comments and replies.
"""

import json
import logging
from pathlib import Path
from typing import Any, Dict

from bs4 import BeautifulSoup

from scrapers.database import WebArchiveDB
from scrapers.utils import parse_arguments

logger = logging.getLogger(__name__)


def write_results_to_file(result: Dict[str, Any], filename: str) -> None:
    """
    Write content to a JSON file, creating directories if they don't exist.

    Args:
        result: The content to write (dictionary that will be serialized to JSON)
        filename: The target filename/path

    Raises:
        PermissionError: If write permissions are denied
        OSError: For other file operation errors
        TypeError: If result cannot be serialized to JSON
    """
    # Convert filename to Path object for easier handling
    file_path = Path(filename)

    # Create parent directories if they don't exist
    file_path.parent.mkdir(parents=True, exist_ok=True)

    try:
        # Write the file
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(result, f, indent=4, ensure_ascii=False)

        logger.info(f"Results have been written to {filename}")
    except TypeError as e:
        logger.error(f"JSON serialization error: {str(e)}")
        raise
    except PermissionError:
        logger.error(f"Permission denied when trying to write to {filename}")
        raise
    except OSError as e:
        logger.error(f"Error writing file: {str(e)}")
        raise


def load_html(file_path: str) -> str:
    """
    Load HTML content from a file.

    Args:
        file_path: Path to the HTML file

    Returns:
        String containing the HTML content

    Raises:
        FileNotFoundError: If the file doesn't exist
        OSError: For other file operation errors
    """
    try:
        with open(file_path, 'r', encoding='utf-8') as file:
            return file.read()
    except FileNotFoundError:
        logger.error(f"HTML file not found: {file_path}")
        raise
    except OSError as e:
        logger.error(f"Error reading HTML file: {str(e)}")
        raise


def extract_bbc_comment_data(soup: Any, selectors: Dict[str, Dict[str, Any]] = None) -> list[Dict[str, Any]]:
    """
    Extract comment data from a BeautifulSoup object using customizable selectors.

    Args:
        soup: BeautifulSoup object containing the parsed HTML
        selectors: Dictionary of CSS selectors and attributes to use for extraction.
                   If None, default selectors will be used.

    Returns:
        list: List of dictionaries containing comment data
    """
    # Default selectors for BBC-style comments
    # Each selector defines the tag type and attributes to look for
    default_selectors = {
        'comment_wrapper': {'tag': 'div', 'attrs': {'class': 'ssrcss-1wh7p7u-CommentWrapper e126ob1s4'}},
        'main_comment': {'tag': 'div', 'attrs': {'class': 'ssrcss-1pptxwy-CommentBody e1qss76f0'}},
        'reply': {'tag': 'div', 'attrs': {'class': 'ssrcss-4odqne-ReplyBody etfy88f4'}},
        'author': {'tag': 'h4', 'attrs': {'class': 'ssrcss-13zgd-Author eg5u43k1'}},
        'post_date': {'tag': 'h4', 'attrs': {'class': 'ssrcss-1dg0ab2-Date eg5u43k0'}},
        'likes': {'tag': 'span', 'attrs': {'data-testid': 'positive-reaction-count'}},
        'dislikes': {'tag': 'span', 'attrs': {'data-testid': 'negative-reaction-count'}}
    }

    # Use provided selectors or fall back to defaults if none provided
    selectors = selectors or default_selectors

    # Initialize empty list to store all comment data
    comments_data = []

    # Find all comment wrappers - these are containers that hold both main comments and their replies
    comments_and_replies = soup.find_all(
        selectors['comment_wrapper']['tag'],
        **selectors['comment_wrapper']['attrs']  # Unpacks the attributes dictionary to be used as keyword arguments
    )

    # Process each comment wrapper individually
    for thread_id, entry in enumerate(comments_and_replies):
        # Extract the main comment from this wrapper
        main_comment = entry.find(
            selectors['main_comment']['tag'],
            **selectors['main_comment']['attrs']
        )

        # If a main comment exists in this wrapper
        if main_comment:
            # Find the author of the main comment
            main_author = entry.find(
                selectors['author']['tag'],
                **selectors['author']['attrs']
            )

            # Find the timestamp for the main comment
            main_post_date = entry.find(
                selectors['post_date']['tag'],
                **selectors['post_date']['attrs']
            )

            # Find the likes count for the main comment
            main_likes = entry.find(
                selectors['likes']['tag'],
                **selectors['likes']['attrs']
            )

            # Find the dislikes count for the main comment
            main_dislikes = entry.find(
                selectors['dislikes']['tag'],
                **selectors['dislikes']['attrs']
            )

            # Add main comment data to our results list
            comments_data.append({
                'thread_id': thread_id,  # Add a unique id for this comment and replies thread
                'comment': main_comment.get_text(strip=True) if main_comment else None,  # Extract clean text
                'user_name': main_author.get_text(strip=True) if main_author else None,  # Extract author name
                'date_time': _parse_timestamp(main_post_date.get_text(strip=True)) if main_author else None,
                # Extract timestamp of post
                'likes': _parse_number(main_likes.get_text(strip=True)) if main_likes else 0,  # Parse like count
                'dislikes': _parse_number(main_dislikes.get_text(strip=True)) if main_dislikes else 0,
                # Parse dislike count
                'is_reply': False,  # Flag this as a main comment, not a reply
            })

        # Extract all replies to this comment
        replies = entry.find_all(
            selectors['reply']['tag'],
            **selectors['reply']['attrs']
        )

        # Handle author extraction for replies - if a main comment exists, skip the first author (already processed)
        reply_authors = entry.find_all(
            selectors['author']['tag'],
            **selectors['author']['attrs']
        )[1:] if main_comment else entry.find_all(  # Skip first author if main comment exists
            selectors['author']['tag'],
            **selectors['author']['attrs']
        )

        # Handle post_date extraction for replies - if a main comment exists, skip the first post_date (already processed)
        reply_post_dates = entry.find_all(
            selectors['post_date']['tag'],
            **selectors['post_date']['attrs']
        )[1:] if main_comment else entry.find_all(  # Skip first post_date if main comment exists
            selectors['post_date']['tag'],
            **selectors['post_date']['attrs']
        )

        # Handle likes extraction for replies - if a main comment exists, skip the first like count
        reply_likes = entry.find_all(
            selectors['likes']['tag'],
            **selectors['likes']['attrs']
        )[1:] if main_comment else entry.find_all(  # Skip first likes if main comment exists
            selectors['likes']['tag'],
            **selectors['likes']['attrs']
        )

        # Handle dislikes extraction for replies - if a main comment exists, skip the first dislike count
        reply_dislikes = entry.find_all(
            selectors['dislikes']['tag'],
            **selectors['dislikes']['attrs']
        )[1:] if main_comment else entry.find_all(  # Skip first dislikes if main comment exists
            selectors['dislikes']['tag'],
            **selectors['dislikes']['attrs']
        )

        # Process each reply individually and match it with its metadata
        for i, reply in enumerate(replies):
            # Get corresponding author for this reply if available, otherwise None
            author = reply_authors[i] if i < len(reply_authors) else None

            # Get corresponding post_date for this reply if available, otherwise None
            post_date = reply_post_dates[i] if i < len(reply_post_dates) else None

            # Get corresponding likes for this reply if available, otherwise None
            likes = reply_likes[i] if i < len(reply_likes) else None

            # Get corresponding dislikes for this reply if available, otherwise None
            dislikes = reply_dislikes[i] if i < len(reply_dislikes) else None

            # Add reply data to our results list
            comments_data.append({
                'thread_id': thread_id,  # Add a unique id for this comment and replies thread
                'comment': reply.get_text(strip=True),  # Extract clean text
                'user_name': author.get_text(strip=True) if author else None,  # Extract author name if available
                'date_time': _parse_timestamp(post_date.get_text(strip=True)) if post_date else None,
                # Extract timestamp of post if available
                'likes': _parse_number(likes.get_text(strip=True)) if likes else 0,  # Parse like count if available
                'dislikes': _parse_number(dislikes.get_text(strip=True)) if dislikes else 0,
                # Parse dislike count if available
                'is_reply': True,  # Flag this as a reply
            })

    # Return the complete list of comments and replies
    return comments_data


def _parse_number(text):
    """
    Parse number from text, handling various formats like '1.2K' (1,200) or '3M' (3,000,000).

    Args:
        text: Text representation of a number

    Returns:
        int: Parsed number
    """
    try:
        # Remove commas and whitespace
        text = text.strip().replace(',', '')

        # Handle thousands (K) suffix
        if 'K' in text:
            return int(float(text.replace('K', '')) * 1000)

        # Handle millions (M) suffix
        elif 'M' in text:
            return int(float(text.replace('M', '')) * 1000000)

        # Regular number without suffix
        return int(text)
    except (ValueError, AttributeError):
        # Return 0 if parsing fails
        return 0


def _parse_timestamp(text):
    """
    Parse date and time from text.

    Args:
        text: Text representation of a date and time
    """
    return text


if __name__ == "__main__":
    # Parse command line arguments
    args = parse_arguments()
    # Setup database connection
    db = WebArchiveDB(db_path='db/database.db', db_table_name=args.table)
    if args.rows:
        db_entries = db.execute_query(f'''SELECT * FROM {db.db_table_name} WHERE ROWID IN ({args.rows})''')
    else:
        db_entries = db.execute_query(f'''SELECT * FROM {db.db_table_name}''')

    for entry in db_entries:
        idx = entry['id']
        site = entry['site']
        input_html_path = entry['html_file']
        output_json_path = f'processed_comments/{db.db_table_name}/id_{idx}.json'

        # Load HTML
        html_content = load_html(input_html_path)
        logger.info(f"Successfully loaded HTML from {input_html_path}")

        if site != 'BBC':
            # Code needs extending to other types of website
            raise NotImplementedError
        else:
            # Extract comments
            soup = BeautifulSoup(html_content, "lxml")
            result = {'content': extract_bbc_comment_data(soup)}  # Same format as ScrapeGraphAI returns
            logger.info("Successfully extracted comments from HTML")

            # Write results
            write_results_to_file(result, output_json_path)
